#![allow(non_snake_case)]

use std::{
    env::args, fmt::write, fs::{self, File, read_to_string}, process::{Command, exit},
};

fn main() {
    let args: Vec<String> = args().collect();
    dbg!(&args);

    let target_file_result = args.get(1);
    if target_file_result.is_none() {
        displayHelp();
    }

    let target_file = target_file_result.unwrap().clone();

    let target_native_result = args.get(2);
    let target_native = if target_file_result.is_some() {
        match target_file_result.unwrap().as_str() {
            "cpp" | "cxx" | "c++" | "cc" => ".cpp",
            "c" => ".c",
            _ => ".c",
        }
    } else {
        "c"
    };
    dbg!(target_native);

    if !target_file.contains(".java") {
        println!("it is probably NOT a java file");
        exit(1);
    }

    let file_contents_result = read_to_string(&target_file);

    if file_contents_result.is_err() {
        println!("File '{target_file}' does not exit");
        exit(1);
    }

    // let file_contents = file_contents_result.unwrap();
    // just in case

    let javac_result = Command::new("javac")
        .arg("-h")
        .arg(".")
        .arg(&target_file)
        .output();
    if javac_result.is_err() {
        println!("Error with file compilation");
    }

    let class_name = target_file.split(".java").nth(0).unwrap().to_owned();
    dbg!(&class_name);
    let header_name = class_name.clone() + ".h";
    let native_impl_name = class_name.clone() + target_native;

    let header_contents_result = read_to_string(&header_name);
    if header_contents_result.is_err() {
        println!("Error with reading the header");
        exit(1);
    }
    let header_contents = header_contents_result.unwrap();


    File::create(&native_impl_name).expect("Error creating file");
    fs::write(&native_impl_name, "
    /* THIS FILE HAS BEEN AUTO GENERATED BY QJNI */
    #include <jni.h>

    ").expect("Error writing to file");

    for line in header_contents.lines() {
        if line.contains("JNIEXPORT ") {
            // fs::write(&native_impl_name, line).expect("Error writing to file");
        }
    }
}

