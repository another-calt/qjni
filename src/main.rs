#![allow(non_snake_case)]

use clap::Parser;
use std::{
    fs::{self, File},
    process::exit,
};

mod args;

fn main() {
    let args = args::Args::parse(); // theyre args, if you couldnt tell

    // locate source file
    let target_file = args.file;
    if !target_file.contains(".java") {
        println!("\x1b[1;31merror\x1b[0m: file must be '.java' file");
        exit(1);
    }

    // locate build file
    let native_target_extension = args.format.unwrap_or(".c".to_string());
    let sperator = if native_target_extension.contains('.') {
        ""
    } else {
        "."
    };
    let native_file_name = args
        .output_name
        .unwrap_or(target_file.split(".java").collect())
        + sperator
        + &native_target_extension;

    // is this the real life
    if std::fs::read(&target_file).is_err() {
        println!("\x1b[1;31merror\x1b[0m: file does not exist");
        exit(1);
    }

    // javac .h
    std::process::Command::new("javac")
        .arg("-h")
        .arg(".")
        .arg(&target_file)
        .output()
        .expect(
            "\x1b[1;31merror\x1b[0m: failed in producing bindings, do you have 'javac' installed?",
        );

    // setup target file
    File::create(&native_file_name).expect("\x1b[1;31merror\x1b[0m: failed to create file");
    fs::write(
        &native_file_name,
        "/* FILE GENERATED BY QJNI */\n#include <jni.h>\n",
    )
    .expect("\x1b[1;31merror\x1b[0m: failed first write to file");

    // find the header file
    let header_target = target_file.split(".java").collect::<String>() + ".h";

    let header_file_contents =
        fs::read_to_string(&header_target).expect("\x1b[1;31merror\x1b[0m: header file not found");

    // build the final file
    for line in header_file_contents.lines() {
        if (line.contains("JNIEXPORT ") & line.contains(" JNICALL Java_"))
            | line.contains("  (JNIEnv *, jobject")
        {
            if line.contains("  (JNIEnv *, jobject") {
                fs::write( // WRITE FOR PARAMETERS
                    &native_file_name,
                    format!(
                        "{}{}\n",
                        fs::read_to_string(&native_file_name).expect(
                            "\x1b[1;31merror\x1b[0m:  failed to read header file when building"
                        ),
                        line.replace(";", " {\n\n}")
                    ),
                )
                .expect("\x1b[1;31merror\x1b[0m: failed to write line when building");
            } else { 
                fs::write( // WRITE FOR DECLARATION
                    &native_file_name,
                    format!(
                        "{}\n{}",
                        fs::read_to_string(&native_file_name).expect(
                            "\x1b[1;31merror\x1b[0m:  failed to read header file when building"
                        ),
                        line.replace(";", " {\n\n}")
                    ),
                )
                .expect("\x1b[1;31merror\x1b[0m: failed to write line when building");
            }
        }
    }
    println!(
        "Native implementation successfully built to: \'{}\'",
        native_file_name
    );
}
